import numpy as np
def sigmoid(x): return 1 / (1 + np.exp(-x))
def sigmoid_deriv(x): return x * (1 - x)
X = np.array([[0,0],[0,1],[1,0],[1,1]])
y = np.array([[0],[1],[1],[0]])
np.random.seed(1)
w1 = np.random.uniform(-1,1,(2,4)); w2 = np.random.uniform(-1,1,(4,1))
for epoch in range(10000):
    h = sigmoid(np.dot(X, w1))
    o = sigmoid(np.dot(h, w2))
    err_o = (y - o) * sigmoid_deriv(o)
    err_h = err_o.dot(w2.T) * sigmoid_deriv(h)
    w2 += h.T.dot(err_o) * 0.5
    w1 += X.T.dot(err_h) * 0.5
print("Predicted output after training:\n", np.round(o, 3))