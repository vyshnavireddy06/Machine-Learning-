import csv

# Sample training data matching the FIND-S example
sample_data = [
    ["Sky", "Temp", "Humid", "Wind", "Water", "Forecast", "Enjoy"],
    ["Sunny", "Warm", "Normal", "Strong", "Warm", "Same", "Yes"],
    ["Sunny", "Warm", "High", "Strong", "Warm", "Same", "Yes"],
    ["Rainy", "Cold", "High", "Strong", "Warm", "Change", "No"],
    ["Sunny", "Warm", "High", "Strong", "Cool", "Change", "Yes"]
]

# Create the CSV file automatically so it exists
with open("training_data.csv", "w", newline="") as file:
    writer = csv.writer(file)
    writer.writerows(sample_data)

# Read training data from CSV file
with open("training_data.csv", "r") as file:
    reader = csv.reader(file)
    data = list(reader)

headers = data[0][:-1]
examples = data[1:]
domains = [
    sorted(set(row[i] for row in examples))
    for i in range(len(headers))
]

# '?' means any value; 'Ø' means the most specific value
n = len(headers)
S = [tuple("Ø" for _ in range(n))]
G = [tuple("?" for _ in range(n))]


def covers(h, x):
    return all(a == "?" or a == b for a, b in zip(h, x))


def more_general_or_equal(h1, h2):
    return all(
        a == "?" or a == b
        for a, b in zip(h1, h2)
    )


def remove_more_general(S):
    return [
        h for h in S
        if not any(
            h != other and more_general_or_equal(other, h)
            for other in S
        )
    ]


def remove_more_specific(G):
    return [
        h for h in G
        if not any(
            h != other and more_general_or_equal(h, other)
            for other in G
        )
    ]


for row in examples:
    x = tuple(row[:-1])
    label = row[-1].strip().lower()

    if label == "yes":
        # Remove G hypotheses that do not cover
        # this positive example
        G = [g for g in G if covers(g, x)]

        new_S = []
        for s in S:
            if all(a == "Ø" for a in s):
                new_S.append(x)
            else:
                h = tuple(
                    a if a == b else "?"
                    for a, b in zip(s, x)
                )
                new_S.append(h)

        S = list(set(new_S))
        S = remove_more_general(S)

    else:
        # Remove S hypotheses covering
        # this negative example
        S = [s for s in S if not covers(s, x)]

        new_G = []
        for g in G:
            if not covers(g, x):
                new_G.append(g)
                continue

            for i in range(n):
                if g[i] == "?":
                    for value in domains[i]:
                        if value != x[i]:
                            h = list(g)
                            h[i] = value
                            h = tuple(h)

                            # Keep specializations at least
                            # as general as some S hypothesis
                            if any(
                                more_general_or_equal(h, s)
                                for s in S
                            ):
                                new_G.append(h)

        G = list(set(new_G))
        G = remove_more_specific(G)

print("Attributes:", headers)
print("Specific boundary S:")
for h in S:
    print(h)

print("General boundary G:")
for h in G:
    print(h)