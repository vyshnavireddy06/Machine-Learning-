import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
from sklearn.metrics import mean_squared_error, r2_score

# Sample dataset
X = np.array([1, 2, 3, 4, 5, 6, 7, 8]).reshape(-1, 1)
y = np.array([2, 5, 10, 17, 26, 37, 50, 65])

# Linear Regression
linear = LinearRegression()
linear.fit(X, y)
y_linear = linear.predict(X)

# Polynomial Regression
poly = PolynomialFeatures(degree=2)
X_poly = poly.fit_transform(X)

model = LinearRegression()
model.fit(X_poly, y)
y_poly = model.predict(X_poly)

print("Linear Regression MSE:", mean_squared_error(y, y_linear))
print("Polynomial Regression MSE:", mean_squared_error(y, y_poly))
print("Linear Regression R2:", r2_score(y, y_linear))
print("Polynomial Regression R2:", r2_score(y, y_poly))

plt.scatter(X, y, color="blue", label="Actual Data")
plt.plot(X, y_linear, color="red", label="Linear Regression")
plt.plot(X, y_poly, color="green", label="Polynomial Regression")
plt.xlabel("X")
plt.ylabel("Y")
plt.legend()
plt.show()